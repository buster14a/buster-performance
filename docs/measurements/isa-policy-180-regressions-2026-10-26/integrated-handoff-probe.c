int main(void)
{
    bool passed = sizeof(X86Instruction) == 16;
    uint32_t known = 0;
    uint32_t lost = 0;
    for (uint32_t i = 0; i < X86_FORM_COUNT; i += 1)
    {
        known += x86_target_requirements[i] != 0;
        lost += incoming_requirements[i] != 0 && x86_target_requirements[i] == 0;
    }
    passed &= lost == 0;
    for (uint32_t i = 0; i < sizeof(handoff_forms) / sizeof(handoff_forms[0]); i += 1)
    {
        passed &= incoming_requirements[handoff_forms[i]] == x86_target_requirements[handoff_forms[i]];
    }
    static const uint64_t features[] = {0, BUSTER_X86_FEATURE(AVX512F), BUSTER_X86_FEATURE(AVX512DQ), BUSTER_X86_FEATURE(AVX512F) | BUSTER_X86_FEATURE(AVX512DQ), UINT64_MAX};
    uint8_t scalar[X86_FORM_COUNT];
    uint8_t vector[X86_FORM_COUNT];
    for (uint32_t t = 0; t < sizeof(features) / sizeof(features[0]); t += 1)
    {
        const X86Target target = {.features = features[t]};
        x86_target_forms_scalar(&target, scalar);
        x86_target_forms(&target, vector);
        passed &= memcmp(scalar, vector, sizeof(scalar)) == 0;
        for (uint32_t i = 0; i < sizeof(handoff_forms) / sizeof(handoff_forms[0]); i += 1)
        {
            const uint16_t form = handoff_forms[i];
            const uint64_t required = incoming_requirements[form];
            const bool allowed = required != 0 && ((required & ~BUSTER_X86_TARGET_KNOWN) & target.features) == (required & ~BUSTER_X86_TARGET_KNOWN);
            passed &= (vector[form] != 0) == allowed;
        }
    }
    printf("565 handoff: %s (%zu concrete masks, %u known / %u forms, %u main-known rows lost, five independent feature sets)\n", passed ? "pass" : "FAIL", sizeof(handoff_forms) / sizeof(handoff_forms[0]), known, X86_FORM_COUNT, lost);
    passed &= fflush(stdout) == 0 && !ferror(stdout);
    return passed ? 0 : 1;
}
