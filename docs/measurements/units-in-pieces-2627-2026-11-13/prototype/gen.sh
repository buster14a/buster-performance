#!/bin/bash
# #2627 prototype: writes OUT/build.ninja, the checker unit of TREE (a configured, built Develop tree) in PIECES pieces,
# each split into PARTS code parts, joined and linked into OUT/compiler the way the tree's Develop build joins and
# links the whole unit; each step rewrites its outputs only when they change (restat), so that `ninja -C OUT` after an
# edit repeats only what the edit changed.
#   gen.sh OUT TREE FILES [PIECES] [PARTS]
set -eu
out=$(realpath "$1"); tree=$(realpath "$2"); files=$(realpath "$3"); pieces=${4:-8}; parts=${5:-6}
here=$(cd "$(dirname "$0")" && pwd)
root=$(grep '^CMAKE_HOME_DIRECTORY:' "$tree/CMakeCache.txt" | cut -d= -f2)
cc=$(grep '^CMAKE_C_COMPILER:' "$tree/CMakeCache.txt" | cut -d= -f2)
llvm=$(dirname "$cc")
cmake=$(grep '^CMAKE_COMMAND:' "$tree/CMakeCache.txt" | cut -d= -f2)
unit=$tree/Develop/develop/main_unit_checker
march=$(ninja -C "$tree" -f build-Develop.ninja -t commands Develop/develop/main_unit_checker/part0.o | tail -1 | grep -o -- '-march=[^ ]*')
link=$(ninja -C "$tree" -f build-Develop.ninja -t commands Develop/compiler.link | tail -1); link=${link#*&& }
link=${link//Develop\/develop\/main_unit_checker\/native.o/$out/native.o}; link=${link/-o Develop\/compiler.link/-o $out/compiler.link}
bake=$(ninja -C "$tree" -f build-Develop.ninja -t commands Develop/compiler | tail -1); bake=${bake##*&& }
bake=${bake//$tree\/Develop\/develop\/main_unit_checker\/native.o/$out/native.o}
bake=${bake//-DINPUT=$tree\/Develop\/compiler.link/-DINPUT=$out/compiler.link}
bake=${bake//-DOUTPUT=$tree\/Develop\/compiler /-DOUTPUT=$out/compiler }
mkdir -p "$out"
{
    echo "# generated by gen.sh"
    echo "rule transform"
    echo "  command = SMALL=${SMALL:-0} MACROS=$out/macros.h python3 $here/pieces.py $files $root/src $pieces $out > $out/transform.log && touch \$out"
    echo "  restat = 1"
    echo "rule cc"
    echo "  command = ROOT=$root CLANG=$cc MARCH=$march $here/piece-cc.sh $out/p\$piece $out/p\$piece.next -MD -MF $out/p\$piece.d && (cmp -s $out/p\$piece.next $out/p\$piece.bc && rm $out/p\$piece.next || mv $out/p\$piece.next $out/p\$piece.bc)"
    echo "  depfile = $out/p\$piece.d"
    echo "  deps = gcc"
    echo "  restat = 1"
    echo "rule owners"
    echo "  command = $here/owners.sh $llvm/llvm-nm $out $pieces"
    echo "  restat = 1"
    echo "rule rename"
    echo "  command = $here/piece_rename $out/p\$piece.bc p\$piece $out/owned\$piece.txt $out/r\$piece.next 2> $out/rename\$piece.log && (cmp -s $out/r\$piece.next $out/r\$piece.bc && rm $out/r\$piece.next || mv $out/r\$piece.next $out/r\$piece.bc)"
    echo "  restat = 1"
    echo "rule split"
    echo "  command = $cmake -DINPUT=$out/r\$piece.bc -DDIRECTORY=$out/s\$piece -DSPLIT=$tree/codegen-tools/presplit -DNM=$llvm/llvm-nm -DPARTITIONS=$parts \"-DOPTIONS=--import;100;--anchor;24;--cohere;150000;--spread;2;--tests-optnone\" -P $root/cmake/BusterCodegenSplit.cmake"
    echo "  restat = 1"
    echo "rule part"
    echo "  command = $cc -x ir $march -gdwarf-4 -gline-tables-only -fno-stack-protector -O3 -Wall -Werror -Wno-unused-command-line-argument -c \$in -o \$out"
    echo "rule locals"
    echo "  command = cat \$in > \$out.next && (cmp -s \$out.next \$out && rm \$out.next || mv \$out.next \$out)"
    echo "  restat = 1"
    echo "rule merge"
    echo "  command = $cmake -DOUTPUT=$out/native.o -DEXPORTS=$unit/exports.txt -DLOCALS=$out/locals.txt \"-DOBJECTS=\$objects\" -DLLD=$llvm/ld.lld -DOBJCOPY=$llvm/llvm-objcopy -DNM=$llvm/llvm-nm -DREADELF=$llvm/llvm-readobj -P $root/cmake/BusterCodegenMerge.cmake"
    echo "rule link"
    echo "  command = cd $tree && $link"
    echo "rule bake"
    echo "  command = cd $tree && $bake"
    echo "build always: phony"
    # The pieces' trees are the transform's outputs, so that Ninja looks at them again after it runs (restat).
    generated=$(grep "^$root/src/" "$files" | awk '!seen[$0]++' | sed "s|^$root/src/||")
    trees=""
    for k in $(seq 0 $((pieces - 1))); do
        trees="$trees $(printf "$out/p$k/%s " $generated)"
    done
    echo "build $out/transform.stamp | $trees: transform always"
    bitcode=""
    for k in $(seq 0 $((pieces - 1))); do
        echo "build $out/p$k.bc: cc || $out/transform.stamp"
        echo "  piece = $k"
        bitcode="$bitcode $out/p$k.bc"
    done
    owned=""
    for k in $(seq 0 $((pieces - 1))); do owned="$owned $out/owned$k.txt"; done
    echo "build $owned: owners $bitcode"
    objects=""; locals=""
    for k in $(seq 0 $((pieces - 1))); do
        echo "build $out/r$k.bc: rename $out/p$k.bc $out/owned$k.txt"
        echo "  piece = $k"
        partfiles=""
        for i in $(seq 0 "$parts"); do partfiles="$partfiles $out/s$k/part$i.bc"; done
        echo "build $out/s$k/split.stamp | $partfiles $out/s$k/locals.txt: split $out/r$k.bc"
        echo "  piece = $k"
        for i in $(seq 0 "$parts"); do
            echo "build $out/s$k/part$i.o: part $out/s$k/part$i.bc || $out/s$k/split.stamp"
            objects="$objects;$out/s$k/part$i.o"
        done
        locals="$locals $out/s$k/locals.txt"
    done
    echo "build $out/locals.txt: locals $locals"
    objects=${objects#;}
    echo "build $out/native.o: merge ${objects//;/ } $out/locals.txt"
    echo "  objects = $objects"
    echo "build $out/compiler.link: link $out/native.o"
    echo "build $out/compiler: bake $out/compiler.link"
    echo "default $out/compiler"
} > "$out/build.ninja"
echo "wrote $out/build.ninja"
