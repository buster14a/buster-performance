// gen-cluster N: writes one C translation unit to standard output holding N
// copies of a self-contained cluster of about 2,000 parser tokens (types, file-
// scope data and seventeen external functions that call each other), each copy's
// identifiers renamed by the suffix _K. No #include and no macros, so the
// preprocessor's work is one pass over the bytes. buster#672's falsifying
// experiment (issue comment 6749355847, section 5).
#include <stdio.h>
#include <stdlib.h>

static const char cluster[] =
    "typedef struct Node@ Node@;\n"
    "struct Node@\n{\n    int key;\n    int weight;\n    Node@* left;\n    Node@* right;\n    unsigned char tag[8];\n};\n"
    "enum Mode@\n{\n    MODE_ADD@,\n    MODE_SUB@,\n    MODE_MUL@,\n    MODE_XOR@,\n    MODE_COUNT@\n};\n"
    "typedef struct\n{\n    Node@ pool[64];\n    int used;\n    long long sum;\n    enum Mode@ mode;\n} Arena@;\n"
    "static Arena@ arena@;\n"
    "static const int table@[16] = { 3, 1, 4, 1, 5, 9, 2, 6, 5, 3, 5, 8, 9, 7, 9, 3 };\n"
    "int counter@ = 7;\n"
    "\n"
    "Node@* node_new@(int key, int weight)\n{\n"
    "    Node@* result = 0;\n"
    "    if (arena@.used < 64)\n    {\n"
    "        result = &arena@.pool[arena@.used];\n"
    "        arena@.used += 1;\n"
    "        result->key = key;\n"
    "        result->weight = weight;\n"
    "        result->left = 0;\n"
    "        result->right = 0;\n"
    "        for (int i = 0; i < 8; i += 1)\n        {\n"
    "            result->tag[i] = (unsigned char)(key * 31 + i);\n"
    "        }\n"
    "    }\n"
    "    return result;\n}\n\n"
    "Node@* node_insert@(Node@* root, Node@* node)\n{\n"
    "    Node@* result = root;\n"
    "    if (root == 0)\n    {\n        result = node;\n    }\n"
    "    else if (node->key < root->key)\n    {\n        root->left = node_insert@(root->left, node);\n    }\n"
    "    else\n    {\n        root->right = node_insert@(root->right, node);\n    }\n"
    "    return result;\n}\n\n"
    "long long node_sum@(const Node@* node, int depth)\n{\n"
    "    long long total = 0;\n"
    "    while (node != 0)\n    {\n"
    "        total += (long long)node->weight * (depth + 1);\n"
    "        total += node_sum@(node->left, depth + 1);\n"
    "        node = node->right;\n"
    "        depth += 1;\n"
    "    }\n"
    "    return total;\n}\n\n"
    "int apply@(enum Mode@ mode, int a, int b)\n{\n"
    "    int result = 0;\n"
    "    switch (mode)\n    {\n"
    "    case MODE_ADD@:\n        result = a + b;\n        break;\n"
    "    case MODE_SUB@:\n        result = a - b;\n        break;\n"
    "    case MODE_MUL@:\n        result = a * b;\n        break;\n"
    "    case MODE_XOR@:\n        result = a ^ b;\n        break;\n"
    "    default:\n        result = -1;\n        break;\n"
    "    }\n"
    "    return result;\n}\n\n"
    "unsigned hash@(const unsigned char* bytes, unsigned long length)\n{\n"
    "    unsigned h = 2166136261u;\n"
    "    for (unsigned long i = 0; i < length; i += 1)\n    {\n"
    "        h ^= bytes[i];\n"
    "        h *= 16777619u;\n"
    "        if ((h & 0xffu) == 0u)\n        {\n            h = (h >> 3) | (h << 29);\n        }\n"
    "    }\n"
    "    return h;\n}\n\n"
    "int reduce@(const int* values, int count, enum Mode@ mode)\n{\n"
    "    int accumulator = values[0];\n"
    "    for (int i = 1; i < count; i += 1)\n    {\n"
    "        accumulator = apply@(mode, accumulator, values[i]);\n"
    "        if (accumulator > 1000000 || accumulator < -1000000)\n        {\n"
    "            accumulator = accumulator % 9973;\n"
    "        }\n"
    "    }\n"
    "    return accumulator;\n}\n\n"
    "void sort@(int* values, int count)\n{\n"
    "    for (int i = 1; i < count; i += 1)\n    {\n"
    "        int value = values[i];\n"
    "        int j = i - 1;\n"
    "        while (j >= 0 && values[j] > value)\n        {\n"
    "            values[j + 1] = values[j];\n"
    "            j -= 1;\n"
    "        }\n"
    "        values[j + 1] = value;\n"
    "    }\n}\n\n"
    "long long build@(int seed)\n{\n"
    "    Node@* root = 0;\n"
    "    int values[16];\n"
    "    arena@.used = 0;\n"
    "    arena@.mode = (enum Mode@)(seed % MODE_COUNT@);\n"
    "    for (int i = 0; i < 16; i += 1)\n    {\n"
    "        values[i] = table@[(i + seed) & 15] * (i + 1) - counter@;\n"
    "        Node@* node = node_new@(values[i], table@[i] + seed);\n"
    "        if (node != 0)\n        {\n            root = node_insert@(root, node);\n        }\n"
    "    }\n"
    "    sort@(values, 16);\n"
    "    arena@.sum = node_sum@(root, 0) + reduce@(values, 16, arena@.mode);\n"
    "    if (root != 0)\n    {\n"
    "        arena@.sum += hash@(root->tag, sizeof(root->tag));\n"
    "    }\n"
    "    counter@ += 1;\n"
    "    return arena@.sum;\n}\n\n"
    "int check@(int rounds)\n{\n"
    "    long long previous = -1;\n"
    "    int changes = 0;\n"
    "    for (int r = 0; r < rounds; r += 1)\n    {\n"
    "        long long value = build@(r * 7 + 3);\n"
    "        if (value != previous)\n        {\n            changes += 1;\n        }\n"
    "        previous = value;\n"
    "        struct { int low; int high; } pair = { (int)(value & 0xffff), (int)((value >> 16) & 0xffff) };\n"
    "        changes += pair.low > pair.high ? 1 : 0;\n"
    "    }\n"
    "    return changes;\n}\n\n"
    "typedef struct\n"
    "{\n"
    "    double m[4][4];\n"
    "} Matrix@;\n"
    "\n"
    "void matrix_multiply@(Matrix@* out, const Matrix@* a, const Matrix@* b)\n"
    "{\n"
    "    for (int i = 0; i < 4; i += 1)\n"
    "    {\n"
    "        for (int j = 0; j < 4; j += 1)\n"
    "        {\n"
    "            double total = 0.0;\n"
    "            for (int k = 0; k < 4; k += 1)\n"
    "            {\n"
    "                total += a->m[i][k] * b->m[k][j];\n"
    "            }\n"
    "            out->m[i][j] = total;\n"
    "        }\n"
    "    }\n"
    "}\n"
    "\n"
    "double matrix_trace@(const Matrix@* a)\n"
    "{\n"
    "    double total = 0.0;\n"
    "    for (int i = 0; i < 4; i += 1)\n"
    "    {\n"
    "        total += a->m[i][i];\n"
    "    }\n"
    "    return total;\n"
    "}\n"
    "\n"
    "int parse_number@(const char* text, int* out)\n"
    "{\n"
    "    int value = 0;\n"
    "    int sign = 1;\n"
    "    int digits = 0;\n"
    "    if (*text == '-')\n"
    "    {\n"
    "        sign = -1;\n"
    "        text += 1;\n"
    "    }\n"
    "    while (*text >= '0' && *text <= '9')\n"
    "    {\n"
    "        value = value * 10 + (*text - '0');\n"
    "        text += 1;\n"
    "        digits += 1;\n"
    "    }\n"
    "    *out = value * sign;\n"
    "    return digits;\n"
    "}\n"
    "\n"
    "enum State@\n"
    "{\n"
    "    STATE_IDLE@,\n"
    "    STATE_WORD@,\n"
    "    STATE_SPACE@,\n"
    "    STATE_DONE@\n"
    "};\n"
    "\n"
    "int count_words@(const char* text)\n"
    "{\n"
    "    enum State@ state = STATE_IDLE@;\n"
    "    int words = 0;\n"
    "    while (state != STATE_DONE@)\n"
    "    {\n"
    "        char c = *text;\n"
    "        text += 1;\n"
    "        switch (state)\n"
    "        {\n"
    "        case STATE_IDLE@:\n"
    "        case STATE_SPACE@:\n"
    "            if (c == 0)\n"
    "            {\n"
    "                state = STATE_DONE@;\n"
    "            }\n"
    "            else if (c != ' ' && c != '\\t')\n"
    "            {\n"
    "                words += 1;\n"
    "                state = STATE_WORD@;\n"
    "            }\n"
    "            break;\n"
    "        case STATE_WORD@:\n"
    "            if (c == 0)\n"
    "            {\n"
    "                state = STATE_DONE@;\n"
    "            }\n"
    "            else if (c == ' ' || c == '\\t')\n"
    "            {\n"
    "                state = STATE_SPACE@;\n"
    "            }\n"
    "            break;\n"
    "        default:\n"
    "            state = STATE_DONE@;\n"
    "            break;\n"
    "        }\n"
    "    }\n"
    "    return words;\n"
    "}\n"
    "\n"
    "unsigned long long bits@(unsigned long long x)\n"
    "{\n"
    "    unsigned long long count = 0;\n"
    "    unsigned long long reversed = 0;\n"
    "    for (int i = 0; i < 64; i += 1)\n"
    "    {\n"
    "        count += (x >> i) & 1ull;\n"
    "        reversed = (reversed << 1) | ((x >> i) & 1ull);\n"
    "    }\n"
    "    return count ^ (reversed & 0xff00ff00ff00ff00ull);\n"
    "}\n"
    "\n"
    "static const char* const names@[4] = { \"alpha\", \"beta gamma\", \"delta epsilon zeta\", \"-42\" };\n"
    "\n"
    "int summary@(int rounds)\n"
    "{\n"
    "    Matrix@ a;\n"
    "    Matrix@ b;\n"
    "    Matrix@ c;\n"
    "    int number = 0;\n"
    "    int total = check@(rounds);\n"
    "    for (int i = 0; i < 4; i += 1)\n"
    "    {\n"
    "        for (int j = 0; j < 4; j += 1)\n"
    "        {\n"
    "            a.m[i][j] = (double)(i + j);\n"
    "            b.m[i][j] = i == j ? 1.0 : 0.5;\n"
    "        }\n"
    "    }\n"
    "    matrix_multiply@(&c, &a, &b);\n"
    "    total += (int)matrix_trace@(&c);\n"
    "    for (int i = 0; i < 4; i += 1)\n"
    "    {\n"
    "        total += count_words@(names@[i]);\n"
    "    }\n"
    "    total += parse_number@(names@[3], &number) + number;\n"
    "    total += (int)(bits@((unsigned long long)total * 0x9e3779b97f4a7c15ull) & 0xffffu);\n"
    "    return total;\n"
    "}\n"
    "\n"
    "int histogram@(const unsigned char* bytes, int length, int* bins)\n"
    "{\n"
    "    int maximum = 0;\n"
    "    int peak = -1;\n"
    "    for (int i = 0; i < 16; i += 1)\n"
    "    {\n"
    "        bins[i] = 0;\n"
    "    }\n"
    "    for (int i = 0; i < length; i += 1)\n"
    "    {\n"
    "        int bin = (bytes[i] >> 4) & 15;\n"
    "        bins[bin] += 1;\n"
    "        if (bins[bin] > maximum)\n"
    "        {\n"
    "            maximum = bins[bin];\n"
    "            peak = bin;\n"
    "        }\n"
    "    }\n"
    "    do\n"
    "    {\n"
    "        maximum -= table@[peak & 15];\n"
    "        peak = (peak + 3) & 15;\n"
    "    } while (maximum > 0);\n"
    "    return peak + maximum;\n"
    "}\n"
    "\n"
    "long long finish@(int rounds)\n"
    "{\n"
    "    int bins[16];\n"
    "    unsigned char bytes[32];\n"
    "    long long total = summary@(rounds);\n"
    "    for (int i = 0; i < 32; i += 1)\n"
    "    {\n"
    "        bytes[i] = (unsigned char)(total >> (i & 7)) ^ (unsigned char)i;\n"
    "    }\n"
    "    total += histogram@(bytes, 32, bins);\n"
    "    for (int i = 0; i < 16; i += 1)\n"
    "    {\n"
    "        total = total * 3 + bins[i];\n"
    "    }\n"
    "    return total;\n"
    "}\n"
    "\n";

int main(int argc, char** argv)
{
    int status = 0;
    if (argc != 2)
    {
        fprintf(stderr, "usage: gen-cluster COPIES\n");
        status = 2;
    }
    else
    {
        long copies = strtol(argv[1], 0, 10);
        for (long k = 0; k < copies; k += 1)
        {
            for (const char* c = cluster; *c != 0; c += 1)
            {
                if (*c == '@')
                {
                    printf("_%ld", k);
                }
                else
                {
                    putchar(*c);
                }
            }
        }
    }
    return status;
}
