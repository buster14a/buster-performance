// A valid base of six intervals in both classes, with a hole in value 0, hints, rematerialization, required uses and
// two fixed ranges, then one change to it each. Each label says where the change is refused: "before" by the input
// validation, which allocates nothing; "after" by the value checks that follow the arena's pushes; "constraint" by
// the register search.
typedef struct Malformed Malformed;
struct Malformed
{
    uint32_t starts[6];
    uint32_t ends[6];
    uint32_t values[6];
    uint32_t allowed[6];
    uint8_t classes[6];
    uint8_t hints[6];
    uint8_t remat[6];
    uint8_t flags[6];
    uint32_t use_offsets[7];
    uint32_t use_positions[6];
    uint8_t use_required[6];
    uint32_t fixed_starts[2];
    uint32_t fixed_ends[2];
    uint32_t fixed_registers[2];
    uint8_t fixed_classes[2];
    Tier1AllocationInput input;
};

static void malformed_base(Malformed* m)
{
    const Malformed base = {
        .starts = { 0, 1, 2, 4, 5, 7 },
        .ends = { 4, 6, 9, 8, 10, 11 },
        .values = { 0, 1, 2, 3, 4, 0 },
        .allowed = { 0xf, 0xf, 0xff, 0xf, 0xff, 0xf },
        .classes = { 0, 0, 1, 0, 1, 0 },
        .hints = { 0, 1, UINT8_MAX, 2, 0, UINT8_MAX },
        .remat = { 0, 1, 0, 0, 1, 0 },
        .flags = { 0, 0, 0, 0, 0, 0 },
        .use_offsets = { 0, 1, 3, 3, 4, 5, 6 },
        .use_positions = { 3, 2, 5, 6, 9, 8 },
        .use_required = { 1, 0, 1, 0, 1, 1 },
        .fixed_starts = { 3, 6 },
        .fixed_ends = { 4, 7 },
        .fixed_registers = { 0x1, 0x2 },
        .fixed_classes = { 0, 1 },
    };
    *m = base;
    m->input = (Tier1AllocationInput){
        .starts = m->starts, .ends = m->ends, .values = m->values, .allowed_registers = m->allowed,
        .classes = m->classes, .flags = m->flags, .hints = m->hints, .rematerializable = m->remat,
        .use_offsets = m->use_offsets, .use_positions = m->use_positions, .use_required = m->use_required,
        .use_count = 6, .count = 6, .value_count = 5, .position_count = 12, .registers = { 0xf, 0xff },
        .fixed = { .starts = m->fixed_starts, .ends = m->fixed_ends, .registers = m->fixed_registers, .classes = m->fixed_classes, .count = 2 },
    };
}

static uint32_t malformed_cases(uint32_t number)
{
    static const char* const labels[] = {
        "malformed-base-valid",
        "malformed-before-empty-interval",
        "malformed-before-end-past-positions",
        "malformed-before-class-out-of-range",
        "malformed-before-value-out-of-range",
        "malformed-before-mask-outside-class",
        "malformed-before-hint-outside-mask",
        "malformed-before-use-outside-interval",
        "malformed-before-uses-unsorted",
        "malformed-before-use-required-not-a-bit",
        "malformed-before-use-offsets-start",
        "malformed-before-fixed-past-positions",
        "malformed-before-gpr-registers-high-bits",
        "malformed-before-unknown-flag",
        "malformed-before-count-past-limit",
        "malformed-after-value-overlap",
        "malformed-after-value-changes-class",
        "malformed-constraint-required-overlap",
    };
    for (uint32_t kind = 0; kind < sizeof(labels) / sizeof(labels[0]); kind += 1)
    {
        static Malformed m;
        malformed_base(&m);
        switch (kind)
        {
        case 1: m.ends[2] = m.starts[2]; break;
        case 2: m.ends[4] = 13; break;
        case 3: m.classes[3] = 2; break;
        case 4: m.values[1] = 5; break;
        case 5: m.allowed[0] = 0x1f; break;
        case 6: m.hints[1] = 5; break;
        case 7: m.use_positions[0] = 4; break;
        case 8: m.use_positions[1] = 5; m.use_positions[2] = 2; break;
        case 9: m.use_required[0] = 2; break;
        case 10: m.use_offsets[0] = 1; break;
        case 11: m.fixed_ends[0] = 13; break;
        case 12: m.input.registers[0] = 0x1000f; break;
        case 13: m.flags[0] = 0x80; break;
        case 14: m.input.count = BUSTER_TIER1_ALLOCATE_MAX_INTERVALS + 1; break;
        case 15: m.starts[5] = 3; break;
        case 16: m.classes[5] = 1; m.allowed[5] = 0xff; break;
        case 17:
            m.input.registers[0] = 0x1;
            m.allowed[0] = m.allowed[1] = m.allowed[3] = m.allowed[5] = 0x1;
            m.hints[0] = 0; m.hints[1] = UINT8_MAX; m.hints[3] = UINT8_MAX;
            m.flags[0] = m.flags[1] = BUSTER_TIER1_ALLOCATE_REQUIRED;
            break;
        default: break;
        }
        sweep_case(number, labels[kind], &m.input);
        number += 1;
    }
    return number;
}

int main(void)
{
    memory_bytes = UINT64_C(64) << 20;
    memory = aligned_alloc(64, memory_bytes);
    if (memory == 0)
    {
        printf("no memory\n");
        return 1;
    }
    memset(memory, 0xa5, memory_bytes);
    dirty_end = 0;
    printf("host_vector %d prefix %d guard %d exhaustive %d memory %" PRIu64 "\n", BUSTER_HOST_VECTOR, CAPACITY_PREFIX, CAPACITY_GUARD, CAPACITY_EXHAUSTIVE, memory_bytes);
    uint32_t number = differential_cases();
    number = fixture_cases(number);
    number = malformed_cases(number);
    printf("cases %u calls %" PRIu64 " violations %" PRIu64 "\n", number, total_calls, total_violations);
    free(memory);
    return total_violations == 0 ? 0 : 1;
}
