#!/bin/bash
# gen.sh > loops.s: #2791's loop variants, each at offsets 0x00, 0x10, 0x20 and 0x30 of a 64-byte line. equal_main is
# main's (and the final head's) `if (p[i] == t) c += 5; else c += 1;`; equal_fused the first head's (ef79b5b), cmove and
# cmovp past a copy into the scratch register; equal_own the same cmovs into a register of their own, then a move back;
# count_main and count_head main's and the head's `if (p[i] > t) c += 3; else c -= 1;`.
body_equal_main='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    xor %edx,%edx
    ucomisd %xmm0,%xmm1
    sete %dl
    setnp %r11b
    and %r11b,%dl
    lea 0x5(%rax),%r8
    add $0x1,%rax
    test %edx,%edx
    cmovne %r8,%rax'
body_equal_fused='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    lea 0x5(%rax),%rdx
    add $0x1,%rax
    ucomisd %xmm0,%xmm1
    mov %rax,%r11
    cmove %rdx,%rax
    cmovp %r11,%rax'
body_equal_own='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    lea 0x5(%rax),%rdx
    add $0x1,%rax
    ucomisd %xmm0,%xmm1
    cmovne %rax,%rdx
    cmovp %rax,%rdx
    mov %rdx,%rax'
body_count_main='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    xor %edx,%edx
    ucomisd %xmm0,%xmm1
    seta %dl
    lea 0x3(%rax),%r8
    sub $0x1,%rax
    test %edx,%edx
    cmovne %r8,%rax'
body_count_head='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    lea 0x3(%rax),%rdx
    sub $0x1,%rax
    ucomisd %xmm0,%xmm1
    cmova %rdx,%rax'
echo '# Generated by gen.sh: #2791 loop variants at fixed offsets of a 64-byte line.'
echo '.section .note.GNU-stack,"",@progbits'
echo '.text'
for v in equal_main equal_fused equal_own count_main count_head; do
    eval "body=\$body_$v"
    for offset in 00 10 20 30; do
        echo
        echo '.p2align 6'
        [ $offset != 00 ] && echo ".skip 0x$offset, 0xcc"
        echo ".globl v_${v}_$offset"
        echo "v_${v}_$offset:"
        echo '    xor %eax,%eax'
        echo '    xor %ecx,%ecx'
        echo '    jmp 2f'
        echo '1:'
        echo "$body"
        echo '    add $0x1,%ecx'
        echo '2: cmp %esi,%ecx'
        echo '    jl 1b'
        echo '    ret'
    done
done
