# cases10.py: updates that are not evaluated: sizeof's, _Alignof's and typeof's operands, a _Generic's controlling
# expression, a builtin's unevaluated argument, and a folded conditional's and logical operator's dead operand.
C('sizeof_post', 'int f(int a) { return sizeof(a++); }\n')
C('sizeof_compound', 'int f(int a) { int b = sizeof(a += 2); return b; }\n')
C('alignof_post', 'int f(int a) { return _Alignof(a++); }\n')
C('conditional_dead', 'int f(int a) { return 1 ? a : a++; }\n')
C('conditional_dead_first', 'int f(int a) { return 0 ? a++ : a; }\n')
C('and_dead', 'int f(int a) { return 0 && a++; }\n')
C('or_dead', 'int f(int a) { return 1 || a++; }\n')
C('typeof_post', 'int f(int a) { __typeof__(a++) b = a; return b; }\n')
C('sizeof_subscript', 'int f(int a, int* p) { return sizeof(p[a++]); }\n')
C('sizeof_address', 'int f(int a) { return sizeof((*(&a))++); }\n')
C('generic_control', 'int f(int a) { return _Generic(a++, int: 1, default: 2); }\n')
C('constant_p', 'int f(int a) { return __builtin_constant_p(a++); }\n')
C('choose_dead', 'int f(int a) { return __builtin_choose_expr(1, a, a++); }\n')
C('sizeof_in_sum', 'long f(int a) { return (long)sizeof(a--) + a; }\n')
C('sizeof_two', 'int f(int* p) { return sizeof((*p)++) + sizeof(p++); }\n')
C('sizeof_array_size', 'int f(int a) { int v[sizeof(a++)]; return sizeof v; }\n')
C('sizeof_argument', 'int g(int); int f(int a) { return g(sizeof(a++)); }\n')
C('sizeof_stored', 'int f(int a) { a = sizeof(a++); return a; }\n')
C('sizeof_added', 'int f(int a) { return a + (int)sizeof(a++); }\n')
