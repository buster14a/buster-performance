#!/bin/bash
# gen.sh > loops.s: #2922's loops as the trees' Tier 1 compiles them (kernels/k_*.s), each at offsets 0x00, 0x10, 0x20 and
# 0x30 of a 64-byte line, after #2791's diag method. truth: a select testing its comparison's truth value (sete, setnp,
# and, test, one cmovne; the base's and the head's best and equal, the base's sum); fused: ucomis and two cmovs (the
# always tree's best and equal, the head's sum). best: `b = p[i] == t ? i : b`; equal: `if (p[i] == t) c += 5; else
# c += 1;`; sum: `s += p[i] == t ? x : y`.
body_best_truth='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    xor %edx,%edx
    ucomisd %xmm0,%xmm1
    sete %dl
    setnp %r11b
    and %r11b,%dl
    test %edx,%edx
    cmovne %ecx,%eax'
body_best_fused='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    ucomisd %xmm0,%xmm1
    mov %eax,%r11d
    cmove %ecx,%eax
    cmovp %r11d,%eax'
body_equal_truth='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    xor %edx,%edx
    ucomisd %xmm0,%xmm1
    sete %dl
    setnp %r11b
    and %r11b,%dl
    lea 0x5(%rax),%r8
    add $0x1,%rax
    test %edx,%edx
    cmovne %r8,%rax'
body_equal_fused='    mov %rcx,%rdx
    movsd (%rdi,%rdx,8),%xmm1
    lea 0x5(%rax),%rdx
    add $0x1,%rax
    ucomisd %xmm0,%xmm1
    mov %rax,%r11
    cmove %rdx,%rax
    cmovp %r11,%rax'
body_sum_truth='    mov %r8,%r9
    movsd (%rdi,%r9,8),%xmm1
    xor %r9d,%r9d
    ucomisd %xmm0,%xmm1
    sete %r9b
    setnp %r11b
    and %r11b,%r9b
    test %r9d,%r9d
    mov %rcx,%r9
    cmovne %rdx,%r9
    add %r9,%rax'
body_sum_fused='    mov %r8,%r9
    movsd (%rdi,%r9,8),%xmm1
    ucomisd %xmm0,%xmm1
    mov %rdx,%r9
    cmovne %rcx,%r9
    cmovp %rcx,%r9
    add %r9,%rax'
echo '# Generated by gen.sh: #2922 loop variants at fixed offsets of a 64-byte line.'
echo '.section .note.GNU-stack,"",@progbits'
echo '.text'
for v in best_truth best_fused equal_truth equal_fused sum_truth sum_fused; do
    eval "body=\$body_$v"
    for offset in 00 10 20 30; do
        echo
        echo '.p2align 6'
        [ $offset != 00 ] && echo ".skip 0x$offset, 0xcc"
        echo ".globl v_${v}_$offset"
        echo "v_${v}_$offset:"
        case $v in
        best_*)
            echo '    mov $0xffffffff,%eax'
            echo '    xor %ecx,%ecx'
            echo '    jmp 2f'
            echo '1:'
            echo "$body"
            echo '    add $0x1,%ecx'
            echo '2: cmp %esi,%ecx'
            ;;
        equal_*)
            echo '    xor %eax,%eax'
            echo '    xor %ecx,%ecx'
            echo '    jmp 2f'
            echo '1:'
            echo "$body"
            echo '    add $0x1,%ecx'
            echo '2: cmp %esi,%ecx'
            ;;
        sum_*)
            echo '    xor %eax,%eax'
            echo '    xor %r8d,%r8d'
            echo '    jmp 2f'
            echo '1:'
            echo "$body"
            echo '    add $0x1,%r8d'
            echo '2: cmp %esi,%r8d'
            ;;
        esac
        echo '    jl 1b'
        echo '    ret'
    done
done
