#!/bin/bash
# The 9700X job's benchmarks of the compiler's own code (.github/workflows/9700x.yml at e22f84ea), one a line:
# NAME<TAB>CPUS<TAB>ARGUMENTS, the arguments split on spaces. Left out: what measures the machine or other programs
# (measure-x86-zen5, measure-mask-spills, benchmark-floors, the linkers' and clang -E's baselines, the programs Tier 1
# and the references compile, which measure-tier1-programs, measure-tier1-rows and measure-helpers time), and the
# isolated and after-scalar repeats of the same commands. Added: -c of sqlite3.c by Tier 1 and -fsyntax-only of the
# checker's unit, the design's second workload.
set -eu
d=$HOME/buster-fast-bench/2559-release-claude
corpus=/var/lib/buster-9700x/corpora/preprocessor-391e729af658
musl=$corpus/libc/musl
pre=$d/inputs/predefines.h
main="-target x86_64-pc-linux-gnu -march=native -Isrc -fwrapv -funsigned-char -DBUSTER_COMPLETE_DRIVER=1 src/buster/compiler/main.c"
mainp="-march=native -Isrc -fwrapv -funsigned-char --predefines $pre -DBUSTER_COMPLETE_DRIVER=1 src/buster/compiler/main.c"
headers="-isystem $corpus/headers/usr/lib/clang/23/include -isystem $corpus/headers/usr/local/include -isystem $corpus/headers/usr/include"
printer="--predefines $corpus/provenance/gnu17-pinned-predefines.txt --target=x86_64-linux-gnu -march=znver5 -std=gnu17 -nostdinc $headers $corpus/sqlite/sqlite3.c"
system="-march=znver5 -nostdinc $headers"
checked="--predefines $corpus/provenance/gnu17-pinned-predefines.txt --clang-features --no-default-config --target=x86_64-linux-gnu -march=znver5 -std=gnu17 -nostdinc $headers"
lowered="--predefines $corpus/provenance/gnu17-pinned-predefines.txt --no-default-config --target=x86_64-linux-gnu -march=znver5 -std=gnu17 -nostdinc $headers $corpus/sqlite/sqlite3.c"
units="--predefines $corpus/provenance/gnu17-pinned-predefines.txt --target=x86_64-linux-gnu -march=znver5 -std=gnu17 -nostdinc $headers"
muslflags="-std=c99 -nostdinc -ffreestanding -D_XOPEN_SOURCE=700 -I $musl/arch/x86_64 -I $musl/arch/generic -I $corpus/musl-generated/obj/src/internal -I $musl/src/include -I $musl/src/internal -I $corpus/musl-generated/obj/include -I $musl/include"
sqlite="-c -DSQLITE_OMIT_LOAD_EXTENSION -DSQLITE_THREADSAFE=0 -DSQLITE_ENABLE_MEMSYS5 -DSQLITE_ENABLE_RTREE -I$corpus/sqlite $corpus/sqlite/sqlite3.c"
benchmarks=(src/buster/compiler/*_benchmark.c)
tests=($d/inputs/c-testsuite/tests/single-exec/*.c)
others=0,1,3,4,5,6,7
row() { printf '%s\t%s\t%s\n' "$1" "$2" "$3"; }
row lexer 2 "benchmark-lexer src"
row x86-zen5 2 "benchmark-x86-zen5"
row x86-disassembler 2 "benchmark-x86-disassembler"
row x86-encoder 2 "benchmark-x86-encoder"
row assembler 2 "benchmark-assembler"
row branch-sizing 2 "benchmark-branch-sizing"
row x86-semantics 2 "benchmark-x86-semantics"
row lanes 0-7 "benchmark-lanes"
row dataflow 2 "benchmark-dataflow"
row ssa 2 "benchmark-ssa"
row dominators 2 "benchmark-dominators"
row dominators-cfg 2 "benchmark-dominators --cfg $d/inputs/dominators-fixture.cfg"
row preprocessor-fuzz 2 "benchmark-preprocessor-fuzz"
row object-writer 2 "benchmark-object-writer"
row debug 2 "benchmark-debug"
row import 2 "benchmark-import"
row bind 2 "benchmark-bind"
row executable 2 "benchmark-executable"
row snapshot 2 "benchmark-snapshot"
row foreign 2 "benchmark-foreign"
row foreign-strings 2 "benchmark-foreign-strings --counts 64,4096 --runs 3"
row link-direct 2 "benchmark-link --cpus 2 --only direct"
row refinement 2 "benchmark-refinement src"
row preprocessor-main 2 "benchmark-preprocessor $main"
row printer-main 2 "benchmark-preprocessor --spelling-cost $main"
row printer-main-markers 2 "benchmark-preprocessor --markers --spelling-cost $main"
row printer-sqlite 2 "benchmark-preprocessor --spelling-cost $printer"
row printer-sqlite-markers 2 "benchmark-preprocessor --markers --spelling-cost $printer"
row preprocessor-tables 2 "benchmark-preprocessor --tables src"
row files-main 0-7 "benchmark-files --rounds $main ${benchmarks[*]}"
row files-musl 0-7 "benchmark-files $muslflags $(echo $musl/src/*/*.c $musl/src/*/x86_64/*.c)"
row files-sqlite 0-7 "benchmark-files --rounds $corpus/sqlite/sqlite3.c"
row files-libc 0-7 "benchmark-files --flat $corpus/libc"
row parser-main 2 "benchmark-parser $mainp"
row parser-pragma 2 "benchmark-parser --passes 1 --only vector tests/parser-handoff/pragma-heavy.c"
row lowering 2 "benchmark-lowering"
row gnu 2 "benchmark-gnu $mainp"
row parser-bindings-main 2 "benchmark-parser-bindings $mainp"
row parser-bindings-sqlite 2 "benchmark-parser-bindings $system $corpus/sqlite/sqlite3.c"
row types 2 "benchmark-types"
row environments 2 "benchmark-environments"
row calling-convention 2 "benchmark-calling-convention"
row checker-wide 2 "benchmark-checker --shape wide"
row checker-chain 2 "benchmark-checker --shape chain --nodes 4096"
row checker-source 2 "benchmark-checker-source $checked $corpus/sqlite/sqlite3.c"
row checker-source-musl 2 "benchmark-checker-source $muslflags $musl/src/regex/regcomp.c"
row lowering-source 2 "benchmark-lowering-source ${tests[*]}"
row sqlite-c 2 "$sqlite -o $d/scratch/bench/sqlite.o"
row sqlite-c-tier1 2 "--tier1 $sqlite -o $d/scratch/bench/sqlite-tier1.o"
row checker-unit-syntax 2 "-fsyntax-only -march=znver5 -Isrc -fwrapv -funsigned-char src/buster/compiler/main_unit_checker.c"
row check-debug 2 "benchmark-check-debug"
row checker-deferred 0-7 "benchmark-checker-deferred --passes 12 --lanes 8 --cpus 2,$others $checked $corpus/sqlite/sqlite3.c"
row check-lanes 0-7 "benchmark-check-lanes --passes 11 --lanes 1,2,3,4,6,8 --cpus 2,$others $lowered"
row check-units 0-7 "benchmark-check-units --lanes 1,2,4,8 --runs 5 -- $units"
row checker-bindings-small 2 "benchmark-checker-bindings $checked --input small"
row checker-bindings-headers 2 "benchmark-checker-bindings $checked --input headers"
row checker-bindings-sqlite 2 "benchmark-checker-bindings --passes 5 $checked $corpus/sqlite/sqlite3.c"
row checker-bindings-pipeline 2 "benchmark-checker-bindings --pipeline --passes 9 $checked $corpus/sqlite/sqlite3.c"
row backend 2 "benchmark-backend"
row unwind 2 "benchmark-unwind --functions 64"
row streaming 0-7 "benchmark-streaming --units 100 --runs 5 --lanes 8 --cpus 0,1"
row backend-source 2 "benchmark-backend-source $lowered"
row ir 2 "benchmark-ir"
row ir-lowering 2 "benchmark-ir-lowering"
row ir-source 2 "benchmark-ir-source $lowered"
row tier1-certificate 2 "benchmark-tier1-certificate $lowered"
row tier1-code-certificate 2 "benchmark-tier1-code-certificate $lowered"
row ir-optimize 2 "benchmark-ir-optimize"
row ir-optimize-passes 2 "benchmark-ir-optimize-passes"
